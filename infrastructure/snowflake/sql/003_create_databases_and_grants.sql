CREATE DATABASE IF NOT EXISTS DATAPULSE_RAW;
CREATE DATABASE IF NOT EXISTS DATAPULSE_STAGING;
CREATE DATABASE IF NOT EXISTS DATAPULSE_ANALYTICS;

CREATE SCHEMA IF NOT EXISTS DATAPULSE_RAW.RAW;
CREATE SCHEMA IF NOT EXISTS DATAPULSE_STAGING.STAGING;
CREATE SCHEMA IF NOT EXISTS DATAPULSE_ANALYTICS.ANALYTICS;

GRANT USAGE ON DATABASE DATAPULSE_RAW TO ROLE DATAPULSE_LOADER;
GRANT USAGE ON SCHEMA DATAPULSE_RAW.RAW TO ROLE DATAPULSE_LOADER;
GRANT CREATE TABLE, INSERT, SELECT ON SCHEMA DATAPULSE_RAW.RAW TO ROLE DATAPULSE_LOADER;

GRANT USAGE ON DATABASE DATAPULSE_RAW TO ROLE DATAPULSE_TRANSFORMER;
GRANT USAGE ON SCHEMA DATAPULSE_RAW.RAW TO ROLE DATAPULSE_TRANSFORMER;
GRANT SELECT ON ALL TABLES IN SCHEMA DATAPULSE_RAW.RAW TO ROLE DATAPULSE_TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA DATAPULSE_RAW.RAW TO ROLE DATAPULSE_TRANSFORMER;

GRANT USAGE ON DATABASE DATAPULSE_STAGING TO ROLE DATAPULSE_TRANSFORMER;
GRANT ALL ON SCHEMA DATAPULSE_STAGING.STAGING TO ROLE DATAPULSE_TRANSFORMER;
GRANT USAGE ON DATABASE DATAPULSE_ANALYTICS TO ROLE DATAPULSE_TRANSFORMER;
GRANT ALL ON SCHEMA DATAPULSE_ANALYTICS.ANALYTICS TO ROLE DATAPULSE_TRANSFORMER;

GRANT USAGE ON DATABASE DATAPULSE_ANALYTICS TO ROLE DATAPULSE_BI_READER;
GRANT USAGE ON SCHEMA DATAPULSE_ANALYTICS.ANALYTICS TO ROLE DATAPULSE_BI_READER;
GRANT SELECT ON ALL TABLES IN SCHEMA DATAPULSE_ANALYTICS.ANALYTICS TO ROLE DATAPULSE_BI_READER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA DATAPULSE_ANALYTICS.ANALYTICS TO ROLE DATAPULSE_BI_READER;
